-- --- yield variants (#83 + #101) ----------------------------------------------
-- The detonation is built once per SELECTABLE YIELD, because a trigger tree is
-- data-stage and cannot be scaled at runtime. Every generated name is derived
-- from the fraction so nothing has to keep a parallel list in step.
--
--   0.25 -> "25", and the carrier is <prefix>detonation-25
--
-- The carrier is an invisible explosion whose `created_effect` IS that step's
-- staged detonation; scripts/impact.lua creates the right one where the shell
-- lands. `created_effect` is declared on EntityPrototype, so it is available on
function N.ex_flash_for(fraction)
  return N.ex_flash .. "-" .. N.yield_tag(fraction)
end

function N.ex_wave_for(fraction, hstep)
  return N.ex_wave .. "-" .. N.yield_tag(fraction) .. "-h" .. tostring(hstep or 1)
