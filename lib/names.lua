function N.yield_tag(fraction)
  return tostring(math.floor(fraction * 100 + 0.5))
end

function N.detonation(fraction)
  return n("detonation-") .. N.yield_tag(fraction)
end

function N.wave_at(tag, kind)
  return n("wave-") .. kind .. "-" .. tag
end

--- Sphere lightning, per strike level. `kind` is bolt, hop, fork, impact, streamer or sky.
function N.lightning(kind, level)
  return n("lightning-") .. kind .. "-" .. tostring(level)
end

--- Lance: core and halo, per yield and per heat step.
function N.lance(layer, fraction, hstep, kind)
  return n("lance-") .. layer .. "-" .. N.yield_tag(fraction) .. "-h" .. tostring(hstep or 1)
         .. (kind == "mid" and "-m" or "")
end

